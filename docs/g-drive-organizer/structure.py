def flatten(nodes, prefix=""):
    """回傳所有相對路徑（含範例資料夾），順序＝建立順序"""
    out = []
    for n in nodes:
        path = (prefix + "\\" + n["name"]) if prefix else n["name"]
        out.append(path)
        out.extend(flatten(n.get("children", []), path))
    return out


